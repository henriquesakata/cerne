const boardTemplate = `{{define "board"}}{{if or .ActiveWorks .IdleWorks .MoreWorks}}
## In progress

{{range .ActiveWorks}}- {{.ID}} — {{.Title}} ({{.Actor}}, since {{.Since}}){{if .PendingHO}} — handoff {{.PendingHO}} pending{{else if .HandoffAt}} — handoff {{.HandoffAt}}: cerne show {{.ID}}{{end}}
{{end}}{{if .MoreWorks}}- {{.MoreWorks}} more active work(s) left out to keep CONTEXT.md within 16 KB: cerne work list
{{end}}{{if .IdleWorks}}- {{.IdleWorks}} more active work(s) idle for over {{.IdleDays}} days (oldest: {{.IdleOldestID}}, idle since {{.IdleOldestSince}}) — triage: 'cerne work list', then 'cerne work done|abandon <id>'
{{end}}{{end}}{{if .PendingHandoffs}}
## Pending handoffs

{{range .PendingHandoffs}}- {{.}}
{{end}}{{if .MoreHandoffs}}- {{.MoreHandoffs}} more: cerne handoff list
{{end}}{{end}}{{end}}`

// contextMaxBytes is the CONTEXT.md ceiling (E-0005 criterion 3): a constant, no setting (N-0121).
const contextMaxBytes = 16 * 1024

// maxPendingHandoffs caps the CONTEXT.md handoff block (F-0368 crit. 10).
const maxPendingHandoffs = 10

// boardData is the "In progress" and "Pending handoffs" sections' data, shared
// by CONTEXT.md and the session-start board (F-0409).
type boardData struct {
	ActiveWorks []workRow
	// Idle* fold the active works with no recent activity into one triage line (F-0319).
	IdleWorks       int
	IdleDays        int
	IdleOldestID    string
	IdleOldestSince string
	// PendingHandoffs are the oldest pending handoffs' list lines (F-0368 crit. 10);
	// MoreHandoffs counts the pending ones past the cap.
	PendingHandoffs []string
	MoreHandoffs    int
	// MoreWorks counts the active works CONTEXT.md's ceiling left out (E-0005).
	MoreWorks int
}

// contextData feeds contextTemplate; Decisions and References carry the
// already-rendered bullet text (markdown link or plain title).
type contextData struct {
	ProjectName string
	boardData
	Features  []featureRow
	Omitted   string // the live features the ceiling left out, with the command (E-0005 criterion 3)
	Closed    string // the count per state of the features not listed (criterion 1)
	Epics     []epicSection
	Decisions []string
	Runbooks  []string
	// MoreDecisions and MoreRunbooks count the lines the ceiling left out.
	MoreDecisions, MoreRunbooks int
	// Knowledge counts the active notes and current references, and
	// NoteComponents renders the components of the active notes with their
	// counts: the one read of the tags (criterion 2), not a line per entity.
	Knowledge      string
	NoteComponents string
}

// workRow is one active work (agent activity, F-0130) in the CONTEXT.md
// "Em andamento" section. Since is CreatedAt formatted YYYY-MM-DD.
type workRow struct {
	ID, Title, Actor, Since, HandoffAt string // HandoffAt: date of the last session handoff, "" when none (F-0339)
	PendingHO                          string // the work's pending HO- (F-0368), "" when none
}

type featureRow struct {
	ID, State, Parent, Module, Title, Docs string
}

// ownerPrioritySuffix renders a feature's title with its owner/priority
// (F-0204) appended as "[owner] [pN]" markers — only the markers present are
// shown, and a feature with neither renders its plain title unchanged.
func ownerPrioritySuffix(f store.Feature) string {
	title := f.Title
	if f.Owner != "" {
		title += " [" + f.Owner + "]"
	}
	if f.Priority != "" {
		title += " [" + f.Priority + "]"
	}
	return title
}

// deliveryLinks renders a feature's delivery URLs (F-0179) as clickable
// markdown, " · "-joined; empty when the feature carries none.
func deliveryLinks(f store.Feature) string {
	var parts []string
	if f.DeliveryCommitURL != "" {
		parts = append(parts, fmt.Sprintf("[commit](%s)", f.DeliveryCommitURL))
	}
	if f.DeliveryMRURL != "" {
		parts = append(parts, fmt.Sprintf("[MR](%s)", f.DeliveryMRURL))
	}
	return strings.Join(parts, " · ")
}

// epicSection is one epic in the CONTEXT.md "Epics" breakdown: the parent
// feature with its live children and implemented/total progress.
type epicSection struct {
	ID, Title   string
	Done, Total int
	Children    []epicChild
}

type epicChild struct {
	ID, State, Title string
}

// Materialize wipes and rebuilds docsDir from the backend at repoDir,
// writing only current-state entities plus a generated CONTEXT.md. When
// scope is non-empty only features of that module are included
// (decisions and references are project-wide). It returns the manifest of
// written files: rel slash path -> sha256 hex (CONTEXT.md included,
// .gitkeep excluded).
func Materialize(repoDir, docsDir, scope string, okf bool) (map[string]string, error) {
	return MaterializeAt(repoDir, docsDir, scope, okf, 14, time.Now())
}

// MaterializeAt is Materialize with an explicit session-board window: active
// works whose activity (latest of UpdatedAt and the last event of any of their
// Refs) is older than now-recentDays are not listed in CONTEXT.md's "In
// progress" section but folded into one triage line (F-0319).
func MaterializeAt(repoDir, docsDir, scope string, okf bool, recentDays int, now time.Time) (map[string]string, error) {
	proj, err := store.LoadProject(repoDir)
	if err != nil {
		return nil, err
	}
	features, err := store.LoadAllFeatures(repoDir)
	if err != nil {
		return nil, err
	}
	decisions, err := store.LoadAllDecisions(repoDir)
	if err != nil {
		return nil, err
	}
	runbooks, err := store.LoadAllRunbooks(repoDir)
	if err != nil {
		return nil, err
	}
	notes, err := store.LoadAllNotes(repoDir)
	if err != nil {
		return nil, err
	}
	references, err := store.LoadAllReferences(repoDir)
	if err != nil {
		return nil, err
	}
	works, err := store.LoadAllWorks(repoDir)
	if err != nil {
		return nil, err
	}
	handoffs, err := store.LoadAllHandoffs(repoDir)
	if err != nil {
		return nil, err
	}
	// Read once, before the wipe: a malformed log must not leave .docs/ deleted.
	events, err := store.ReadEvents(repoDir)
	if err != nil {
		return nil, err
	}

	if err := os.RemoveAll(docsDir); err != nil {
		return nil, err
	}
	if err := os.MkdirAll(docsDir, 0o755); err != nil {
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(docsDir, ".gitkeep"), nil, 0o644); err != nil {
		return nil, err
	}

	manifest := map[string]string{}
	blocks := map[string]string{}
	descs := map[string]string{} // entity id -> derived OKF description (okf only)
	data := contextData{ProjectName: proj.Name}
	data.boardData = boardDataOf(works, events, handoffs, now, recentDays)

	var live []store.Feature                // in-scope live features, in display order
	rows := map[string]featureRow{}         // their table rows, by id
	closed := map[domain.FeatureState]int{} // in-scope features not listed, by state
	var progress []store.Feature            // live and done: the epics' implemented/total
	for _, f := range features {
		if scope != "" && f.Module != scope {
			continue
		}
		if !slices.Contains(contextGroupOrder, f.State) {
			closed[f.State]++
		}
		if f.State == domain.StateDone || slices.Contains(contextGroupOrder, f.State) {
			progress = append(progress, f)
		}
	}
	for _, state := range contextGroupOrder {
		for _, f := range features { // already sorted by ID
			if f.State != state {
				continue
			}
			if scope != "" && f.Module != scope {
				continue
			}
			row := featureRow{ID: f.ID, State: string(f.State), Parent: f.Parent, Module: f.Module, Title: ownerPrioritySuffix(f)}
			if featureIsCurrent(f) {
				docs, err := copyFeatureDocs(repoDir, docsDir, f, okf, manifest, blocks, descs)
				if err != nil {
					return nil, err
				}
				row.Docs = docs
			}
			// Delivery links (F-0179) share the Docs cell: an extra column would
			// widen every row for a mostly-empty field.
			if links := deliveryLinks(f); links != "" {
				if row.Docs != "" {
					row.Docs += " · "
				}
				row.Docs += links
			}
			rows[f.ID] = row
			live = append(live, f)
		}
	}
	data.Closed = closedLine(closed)

	for _, d := range decisions {
		if !decisionIsCurrent(d) {
			continue
		}
		meta := okfMeta{Type: "decision", Title: d.Title, Timestamp: okfTime(d.UpdatedAt)}
		line, err := copyEntry(repoDir, docsDir, "decisions", d.ID, d.Title, manifest, blocks, okf, meta, descs)
		if err != nil {
			return nil, err
		}
		if len(d.Facets) > 0 {
			line += " · facet " + strings.Join(d.Facets, ",")
		}
		if len(d.Components) > 0 {
			line += " · comp " + strings.Join(d.Components, ",")
		}
		data.Decisions = append(data.Decisions, line)
	}

	for _, rb := range runbooks {
		if !runbookIsCurrent(rb) {
			continue
		}
		meta := okfMeta{Type: "runbook", Title: rb.Title, Timestamp: okfTime(rb.UpdatedAt)}
		line, err := copyEntry(repoDir, docsDir, "runbooks", rb.ID, rb.Title, manifest, blocks, okf, meta, descs)
		if err != nil {
			return nil, err
		}
		data.Runbooks = append(data.Runbooks, line)
	}

	// Notes and references are still materialized whole; the map carries
	// only their counts and the components of the notes (E-0005 criterion 2).
	activeNotes, currentRefs := 0, 0
	noteComps := map[string]int{}
	for _, n := range notes {
		if !noteIsCurrent(n) {
			continue
		}
		meta := okfMeta{Type: "note", Title: n.Title, Timestamp: okfTime(n.UpdatedAt), Informs: n.Informs}
		if _, err := copyEntry(repoDir, docsDir, "notes", n.ID, n.Title, manifest, blocks, okf, meta, descs); err != nil {
			return nil, err
		}
		activeNotes++
		for _, c := range n.Components {
			noteComps[c]++
		}
	}

	for _, r := range references {
		if !referenceIsCurrent(r) {
			continue
		}
		meta := okfMeta{Type: "reference", Title: r.Title, Timestamp: okfTime(r.UpdatedAt), Resource: r.URL, External: r.External, Informs: r.Informs}
		if _, err := copyEntry(repoDir, docsDir, "references", r.ID, r.Title, manifest, blocks, okf, meta, descs); err != nil {
			return nil, err
		}
		currentRefs++
	}
	if activeNotes+currentRefs > 0 {
		data.Knowledge = plural(activeNotes, "active note") + ", " + plural(currentRefs, "current reference") + "."
	}

	if err := copyWiki(repoDir, docsDir, manifest); err != nil {
		return nil, err
	}

	if err := store.SaveErrataBlocks(docsDir, blocks); err != nil {
		return nil, err
	}

	if okf {
		idPath := entityPaths(features, decisions, runbooks, notes, references, manifest)
		sections := okfIndexSections(features, decisions, references, notes, runbooks, idPath, descs)
		if err := writeRootIndex(docsDir, proj.Name, sections, manifest); err != nil {
			return nil, err
		}
		if err := writeLog(docsDir, events, idPath, manifest); err != nil {
			return nil, err
		}
	}

	body, err := fitContext(data, live, rows, progress, noteComps)
	if err != nil {
		return nil, err
	}
	sum, err := writeFile(docsDir, "CONTEXT.md", body)
	if err != nil {
		return nil, err
	}
	manifest["CONTEXT.md"] = sum
	return manifest, nil
}

// fitContext renders CONTEXT.md within contextMaxBytes (E-0005 criterion 3).
// Everything is listed when it fits. Otherwise lines go in this order, as few
// as fit (a binary search over how many, so a few renders, not one per line):
// the candidate, approved and implemented features (contextKeepOrder read
// backwards, oldest first within a state), then the last active decisions,
// runbooks and works, then the in-development features (oldest first), then
// the least used note components. Each section says how many it left out and
// the command that lists them, so the in-development rows outlive a long
// decision list and the tag list with the group search outlives everything. A
// map that still does not fit (a board of thousands of works with no other
// line left) is cut at the last whole line under the ceiling.
func fitContext(data contextData, live []store.Feature, rows map[string]featureRow, progress []store.Feature, comps map[string]int) ([]byte, error) {
	tmpl, err := template.New("context").Parse(boardTemplate + contextTemplate)
	if err != nil {
		return nil, err
	}
	var keepDev, keepLow []store.Feature // newest first within a state
	for _, state := range contextKeepOrder {
		for i := len(live) - 1; i >= 0; i-- {
			if live[i].State != state {
				continue
			}
			if state == domain.StateInDevelopment {
				keepDev = append(keepDev, live[i])
			} else {
				keepLow = append(keepLow, live[i])
			}
		}
	}
	// The components leave the least used first; they print alphabetically.
	byUse := slices.SortedFunc(maps.Keys(comps), func(a, b string) int {
		if d := comps[b] - comps[a]; d != 0 {
			return d
		}
		return strings.Compare(a, b)
	})
	total := len(keepLow) + len(data.Decisions) + len(data.Runbooks) + len(data.ActiveWorks) + len(keepDev) + len(byUse)
	render := func(k int) ([]byte, error) {
		take := func(n int) int { x := min(n, k); k -= x; return x }
		lowCut := take(len(keepLow))
		decCut := take(len(data.Decisions))
		rbCut := take(len(data.Runbooks))
		workCut := take(len(data.ActiveWorks))
		devCut := take(len(keepDev))
		compCut := take(len(byUse))

		d := data
		d.Decisions, d.MoreDecisions = data.Decisions[:len(data.Decisions)-decCut], decCut
		d.Runbooks, d.MoreRunbooks = data.Runbooks[:len(data.Runbooks)-rbCut], rbCut
		d.ActiveWorks, d.MoreWorks = data.ActiveWorks[:len(data.ActiveWorks)-workCut], workCut
		kept := map[string]bool{}
		left := map[domain.FeatureState]int{}
		for i, f := range keepDev {
			if i < len(keepDev)-devCut {
				kept[f.ID] = true
			} else {
				left[f.State]++
			}
		}
		for i, f := range keepLow {
			if i < len(keepLow)-lowCut {
				kept[f.ID] = true
			} else {
				left[f.State]++
			}
		}
		d.Features, d.Omitted = nil, ""
		var shown []store.Feature
		for _, f := range live {
			if kept[f.ID] {
				d.Features = append(d.Features, rows[f.ID])
				shown = append(shown, f)
			}
		}
		d.Epics = epicSections(shown, progress)
		if n := lowCut + devCut; n > 0 {
			var parts []string
			for _, s := range contextKeepOrder {
				if left[s] > 0 {
					parts = append(parts, fmt.Sprintf("%d %s", left[s], s))
				}
			}
			d.Omitted = fmt.Sprintf("%s left out to keep this file within 16 KB (%s) — 'cerne feature list --state <state>' lists them.",
				plural(n, "live feature"), strings.Join(parts, ", "))
		}
		shownComps := slices.Sorted(slices.Values(byUse[:len(byUse)-compCut]))
		parts := make([]string, 0, len(shownComps))
		for _, c := range shownComps {
			parts = append(parts, fmt.Sprintf("%s (%d)", c, comps[c]))
		}
		d.NoteComponents = strings.Join(parts, ", ")
		if compCut > 0 {
			d.NoteComponents += fmt.Sprintf(" and %d more ('cerne tags' lists them)", compCut)
		}
		var buf bytes.Buffer
		if err := tmpl.Execute(&buf, d); err != nil {
			return nil, err
		}
		return buf.Bytes(), nil
	}
	fits := func(k int) ([]byte, bool, error) {
		b, err := render(k)
		return b, len(b) <= contextMaxBytes, err
	}
	body, ok, err := fits(0)
	if err != nil || ok {
		return body, err
	}
	lo, hi := 1, total // the fewest lines left out that fit
	for lo < hi {
		mid := (lo + hi) / 2
		_, ok, err := fits(mid)
		if err != nil {
			return nil, err
		}
		if ok {
			hi = mid
		} else {
			lo = mid + 1
		}
	}
	// A section's "N more" line can outweigh the line it replaces, so the
	// size is not strictly monotone in k: step on until it fits.
	for ; lo <= total; lo++ {
		if body, ok, err = fits(lo); err != nil || ok {
			return body, err
		}
	}
	const cut = "\n_Cut at 16 KB: run 'cerne brief' for the whole map._\n"
	body = body[:bytes.LastIndexByte(body[:contextMaxBytes-len(cut)], '\n')]
	return append(body, cut...), nil
}

// closedLine counts the features the map does not list, by state.
func closedLine(closed map[domain.FeatureState]int) string {
	var parts []string
	for _, s := range contextClosedOrder {
		if closed[s] > 0 {
			parts = append(parts, fmt.Sprintf("%d %s", closed[s], s))
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return "Not listed: " + strings.Join(parts, ", ") + " — 'cerne feature list --state <state>' lists them."
}

// plural is "n word" with an s when n is not 1.
func plural(n int, word string) string {
	if n == 1 {
		return "1 " + word
	}
	return fmt.Sprintf("%d %ss", n, word)
}

// boardDataOf builds the in-progress board from the works, events and handoffs of
// a backend: active works, the idle ones folded into one line, and the pending
// handoffs (F-0409: one builder for CONTEXT.md and the session start).
func boardDataOf(works []store.Work, events []domain.Event, handoffs []store.Handoff, now time.Time, recentDays int) boardData {
	data := boardData{IdleDays: recentDays}
	lastEvent := map[string]time.Time{}
	for _, ev := range events {
		if ev.At.After(lastEvent[ev.EntityID]) {
			lastEvent[ev.EntityID] = ev.At
		}
	}
	pendingHO := map[string]string{} // work -> its pending HO-
	hasHO := map[string]bool{}       // works that passed any HO-: no F-0339 fallback for them
	titles := map[string]string{}
	for _, w := range works {
		titles[w.ID] = w.Title
	}
	var pending []store.Handoff
	for _, h := range handoffs {
		hasHO[h.FromWork] = true
		if h.State == domain.HandoffPending {
			pending = append(pending, h)
			pendingHO[h.FromWork] = h.ID
		}
	}
	slices.SortStableFunc(pending, func(a, b store.Handoff) int { return a.CreatedAt.Compare(b.CreatedAt) })
	for i, h := range pending {
		if i == maxPendingHandoffs {
			data.MoreHandoffs = len(pending) - i
			break
		}
		data.PendingHandoffs = append(data.PendingHandoffs, h.Line(titles[h.FromWork], now))
	}
	cutoff := now.UTC().AddDate(0, 0, -recentDays)
	var oldestAt time.Time
	for _, w := range works {
		if w.State != domain.WorkActive {
			continue
		}
		activity := w.UpdatedAt
		for _, ref := range w.Refs {
			if t := lastEvent[ref]; t.After(activity) {
				activity = t
			}
		}
		activity = activity.UTC()
		if activity.Before(cutoff) {
			if data.IdleWorks == 0 || activity.Before(oldestAt) {
				oldestAt, data.IdleOldestID = activity, w.ID
				data.IdleOldestSince = activity.Format("2006-01-02")
			}
			data.IdleWorks++
			continue
		}
		row := workRow{
			ID:    w.ID,
			Title: w.Title,
			Actor: w.Actor,
			Since: w.CreatedAt.Format("2006-01-02"),
		}
		if w.HandoffAt != nil && !hasHO[w.ID] {
			row.HandoffAt = w.HandoffAt.UTC().Format("2006-01-02")
		}
		row.PendingHO = pendingHO[w.ID]
		data.ActiveWorks = append(data.ActiveWorks, row)
	}
	return data
}

// RenderBoard is the board as text: the CONTEXT.md sections, or one line when
// there is no active work nor pending handoff.
func RenderBoard(works []store.Work, events []domain.Event, handoffs []store.Handoff, now time.Time, recentDays int) (string, error) {
	data := boardDataOf(works, events, handoffs, now, recentDays)
	tmpl, err := template.New("session").Parse(boardTemplate + `{{template "board" .}}`)
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", err
	}
	if out := strings.TrimLeft(buf.String(), "\n"); out != "" {
		return out, nil
	}
	return "- no active work\n", nil
}

// copyWiki projects every compiled page under content/wiki/ into .docs/wiki/
// verbatim, adding each to the manifest. Wiki is a versioned synthesis
// artifact, so it is project-wide and ignores the feature scope filter. A
// backend with no compiled pages is a no-op.
func copyWiki(repoDir, docsDir string, manifest map[string]string) error {
	wikiRoot := filepath.Join(repoDir, "content", "wiki")
	return filepath.WalkDir(wikiRoot, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				return nil
			}
			return err
		}
		if d.IsDir() || !strings.HasSuffix(d.Name(), ".md") {
			return nil
		}
		body, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		under, err := filepath.Rel(wikiRoot, p)
		if err != nil {
			return err
		}
		rel := "wiki/" + filepath.ToSlash(under)
		sum, err := writeFile(docsDir, rel, body)
		if err != nil {
			return err
		}
		manifest[rel] = sum
		return nil
	})
}

// copyFeatureDocs copies the feature's existing lifecycle documents into
// current/features/<ID>-<slug>/ and returns the rendered Docs column:
// "[spec](path), [plan](path)" for the docs that exist. Under okf, each doc is
// wrapped in OKF frontmatter (type: spec|plan|result) and a generated index.md
// (type: feature) is emitted carrying the feature's lifecycle fields.
func copyFeatureDocs(repoDir, docsDir string, f store.Feature, okf bool, manifest, blocks, descs map[string]string) (string, error) {
	dirName := entryName(f.ID, f.Title)
	var links, written []string
	var description string
	for _, filename := range featureDocFilenames {
		src := filepath.Join(repoDir, "content", "features", f.ID, filename)
		body, err := os.ReadFile(src)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return "", err
		}
		if okf {
			if filename == "spec.md" {
				if description = specDescription(body, descriptionMaxRunes); description != "" {
					descs[f.ID] = description
				}
			}
			docType := strings.TrimSuffix(filename, ".md")
			body = okfFrontmatter(okfMeta{Type: docType, Title: f.Title, Timestamp: okfTime(f.UpdatedAt)}, body)
		}
		rel := "current/features/" + dirName + "/" + filename
		var sum string
		if filename == "spec.md" {
			sum, err = writeWithErrata(repoDir, docsDir, rel, f.ID, false, body, blocks)
		} else {
			sum, err = writeFile(docsDir, rel, body)
		}
		if err != nil {
			return "", err
		}
		manifest[rel] = sum
		links = append(links, fmt.Sprintf("[%s](%s)", strings.TrimSuffix(filename, ".md"), rel))
		written = append(written, filename)
	}
	if okf {
		// An authored doc named index.md wins over the generated OKF index:
		// overwriting authored content is never acceptable, and OKF tolerates
		// a feature dir whose index is hand-written (F-0166 C8).
		authored, err := os.ReadFile(filepath.Join(repoDir, "content", "features", f.ID, "index.md"))
		switch {
		case err == nil:
			rel := "current/features/" + dirName + "/index.md"
			sum, werr := writeFile(docsDir, rel, authored)
			if werr != nil {
				return "", werr
			}
			manifest[rel] = sum
		case !errors.Is(err, os.ErrNotExist):
			return "", err
		default:
			if err := writeFeatureIndex(docsDir, dirName, f, description, written, manifest); err != nil {
				return "", err
			}
		}
	}
	return strings.Join(links, ", "), nil
}

// writeFeatureIndex emits the OKF index.md concept for a feature: a type:feature
// frontmatter carrying the lifecycle fields (state, parent, module→tags) plus
// sibling links to whichever lifecycle docs were materialized. The index is
// generated, so its cerne_id comes from the feature id.
func writeFeatureIndex(docsDir, dirName string, f store.Feature, description string, written []string, manifest map[string]string) error {
	var tags []string
	if f.Module != "" {
		tags = []string{f.Module}
	}
	// D-0003: the facet/component axes join module in the OKF tag list.
	tags = append(tags, f.Facets...)
	tags = append(tags, f.Components...)
	meta := okfMeta{
		Type:        "feature",
		Title:       f.Title,
		Description: description,
		Timestamp:   okfTime(f.UpdatedAt),
		Tags:        tags,
		State:       string(f.State),
		Parent:      f.Parent,
		CerneID:     f.ID,
	}
	var body strings.Builder
	body.WriteString("# " + f.Title + "\n")
	for _, filename := range written {
		body.WriteString(fmt.Sprintf("\n- [%s](%s)", strings.TrimSuffix(filename, ".md"), filename))
	}
	body.WriteString("\n")
	rel := "current/features/" + dirName + "/index.md"
	sum, err := writeFile(docsDir, rel, okfFrontmatter(meta, []byte(body.String())))
	if err != nil {
		return err
	}
	manifest[rel] = sum
	return nil
}

// copyEntry copies content/<kind>/<ID>.md into current/<kind>/<ID>-<slug>.md
// and returns the CONTEXT.md bullet text: a markdown link when the content
// document exists, the plain "<ID> — <title>" otherwise.
func copyEntry(repoDir, docsDir, kind, id, title string, manifest, blocks map[string]string, okf bool, meta okfMeta, descs map[string]string) (string, error) {
	label := fmt.Sprintf("%s — %s", id, title)
	body, err := os.ReadFile(filepath.Join(repoDir, "content", kind, id+".md"))
	if errors.Is(err, os.ErrNotExist) {
		return label, nil
	}
	if err != nil {
		return "", err
	}
	if okf {
		if meta.Description = firstProseParagraph(body, descriptionMaxRunes); meta.Description != "" {
			descs[id] = meta.Description
		}
		body = okfFrontmatter(meta, body)
	}
	rel := "current/" + kind + "/" + entryName(id, title) + ".md"
	sum, err := writeWithErrata(repoDir, docsDir, rel, id, kind == "runbooks", body, blocks)
	if err != nil {
		return "", err
	}
	manifest[rel] = sum
	return fmt.Sprintf("[%s](%s)", label, rel), nil
}

// entityPaths maps each entity id to its materialized rel path — the feature's
// generated index.md or the single-file concept doc — including only entities
// this pull actually wrote (manifest membership), so log.md/index.md links
// never dangle by construction.
func entityPaths(features []store.Feature, decisions []store.Decision, runbooks []store.Runbook, notes []store.Note, references []store.Reference, manifest map[string]string) map[string]string {
	idPath := map[string]string{}
	include := func(id, rel string) {
		if _, ok := manifest[rel]; ok {
			idPath[id] = rel
		}
	}
	for _, f := range features {
		include(f.ID, "current/features/"+entryName(f.ID, f.Title)+"/index.md")
	}
	for _, d := range decisions {
		include(d.ID, "current/decisions/"+entryName(d.ID, d.Title)+".md")
	}
	for _, rb := range runbooks {
		include(rb.ID, "current/runbooks/"+entryName(rb.ID, rb.Title)+".md")
	}
	for _, n := range notes {
		include(n.ID, "current/notes/"+entryName(n.ID, n.Title)+".md")
	}
	for _, r := range references {
		include(r.ID, "current/references/"+entryName(r.ID, r.Title)+".md")
	}
	return idPath
}

// epicSections builds the CONTEXT.md "Epics" breakdown from the features shown
// in the table: every feature that has at least one child among them, with its
// children and implemented/total progress. The caller passes only shown
// (in-scope, non-terminal) features, so children are already live; epics are
// sorted by ID. A child whose parent is not among the shown features (e.g. the
// epic itself is terminal) is left to the lint, not rendered here.
func epicSections(shown, progress []store.Feature) []epicSection {
	byID := make(map[string]store.Feature, len(shown))
	for _, f := range shown {
		byID[f.ID] = f
	}
	childrenByParent := store.ChildrenByParent(shown)
	progressByParent := store.ChildrenByParent(progress)
	epicIDs := make([]string, 0, len(childrenByParent))
	for id := range childrenByParent {
		epicIDs = append(epicIDs, id)
	}
	sort.Strings(epicIDs)

	var sections []epicSection
	for _, id := range epicIDs {
		epic, ok := byID[id]
		if !ok {
			continue
		}
		children := childrenByParent[id]
		done, total := store.EpicProgress(progressByParent[id])
		sec := epicSection{ID: id, Title: epic.Title, Done: done, Total: total}
		for _, c := range children {
			sec.Children = append(sec.Children, epicChild{ID: c.ID, State: string(c.State), Title: c.Title})
		}
		sections = append(sections, sec)
	}
	return sections
}

// maxEntryName bounds the materialized name stem (ID + "-" + slug) used for both
// single-file entries (<stem>.md) and feature directories (<stem>/). NAME_MAX is
// 255 bytes on macOS APFS/HFS+ and most Linux filesystems; we keep a margin.
// Without this cap a very long title overflows NAME_MAX and `cerne pull` aborts
// with ENAMETOOLONG on the offending entry, blocking materialization of the whole
// snapshot for everyone on such a filesystem.
const maxEntryName = 200

// entryName joins ID and slugified title; just the ID when the title slugifies to
// nothing. The result is capped at maxEntryName bytes (trimmed back to a hyphen
// boundary when possible) so an over-long title cannot produce a name that exceeds
// the filesystem's NAME_MAX — the ID prefix keeps it unique regardless. slug.Make
// emits only [a-z0-9-], so truncating by bytes never splits a multibyte rune.
func entryName(id, title string) string {
	s := slug.Make(title)
	if s == "" {
		return id
	}
	name := id + "-" + s
	if len(name) <= maxEntryName {
		return name
	}
	name = name[:maxEntryName]
	if i := strings.LastIndexByte(name, '-'); i > len(id) {
		name = name[:i]
	}
	return strings.TrimRight(name, "-")
}

// writeFile writes body to <docsDir>/<rel> (rel slash-separated), creating
// parent dirs, and returns the sha256 hex of body.
func writeFile(docsDir, rel string, body []byte) (string, error) {
	path := filepath.Join(docsDir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(path, body, 0o644); err != nil {
		return "", err
	}
	sum := sha256.Sum256(body)
	return hex.EncodeToString(sum[:]), nil
}

var mergedRevRe = regexp.MustCompile(`^\D*(\d+)\D*$`)

// writeWithErrata writes body with the entity's errata appended as a generated
// block (B-0012) and returns the manifest hash of the body ALONE: the block is
// derived from the backend, so it is never a local edit, and push strips it.
// Runbook items already folded into the body show as one line (F-0351).
func writeWithErrata(repoDir, docsDir, rel, id string, runbook bool, body []byte, blocks map[string]string) (string, error) {
	er, err := store.LoadErrata(repoDir, id)
	if err != nil {
		return "", err
	}
	var merged func(store.ErrataItem) string
	if runbook {
		merged = func(it store.ErrataItem) string {
			l := it.ID + " merged"
			// the stored label is localized ("revisão N"): take its number
			if m := mergedRevRe.FindStringSubmatch(it.Merged); m != nil {
				l += " into revision " + m[1]
			}
			l += " — shown in the body"
			if it.Target != "" {
				l += " under " + it.Target
			}
			return l
		}
	}
	block := store.ErrataBlock(string(stripFrontmatter([]byte(er))), merged)
	if _, err := writeFile(docsDir, rel, append(append([]byte{}, body...), block...)); err != nil {
		return "", err
	}
	if block != "" {
		blocks[rel] = block // the exact text, so push strips it and nothing else
	}
	sum := sha256.Sum256(body)
	return hex.EncodeToString(sum[:]), nil
}
