// Package materialize projects the current state of a cerne backend into a
// local .docs/ tree: only live entities are written, so AI agents never see
// superseded or rejected history.
package materialize

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	"gitlab.com/rockt/cerne/internal/domain"
	"gitlab.com/rockt/cerne/internal/slug"
	"gitlab.com/rockt/cerne/internal/store"
)

// featureDocFilenames are the lifecycle documents copied per feature, in
// the order their links appear in the CONTEXT.md Docs column.
var featureDocFilenames = []string{"spec.md", "plan.md", "result.md"}

// contextGroupOrder is the fixed display order of the CONTEXT.md feature
// table; terminal states (rejected, superseded) are never listed.
var contextGroupOrder = []domain.FeatureState{
	domain.StateInDevelopment,
	domain.StateApproved,
	domain.StateCandidate,
	domain.StateImplemented,
}

// materializedStates are the feature states whose content documents are
// copied into .docs/. Implemented features stay listed in CONTEXT.md but
// their content is not materialized (promotion-on-completion rule).
var materializedStates = map[domain.FeatureState]bool{
	domain.StateCandidate:     true,
	domain.StateApproved:      true,
	domain.StateInDevelopment: true,
}

const contextTemplate = `# {{.ProjectName}} — current state

> Generated by cerne. Do not edit: run 'cerne pull' to update.
> History and superseded documents: 'cerne search'.
> For "why/how we decided X", use 'cerne ask "<question>"' — a synthesized, cited answer, no need to open file by file.

## Features

{{if .Features}}| ID | State | Epic | Module | Title | Docs |
|---|---|---|---|---|---|
{{range .Features}}| {{.ID}} | {{.State}} | {{.Parent}} | {{.Module}} | {{.Title}} | {{.Docs}} |
{{end}}{{else}}_None._
{{end}}
## Epics

{{if .Epics}}{{range .Epics}}### {{.ID}} — {{.Title}} ({{.Done}}/{{.Total}} implemented)

{{range .Children}}- {{.ID}} — {{.Title}} ({{.State}})
{{end}}
{{end}}{{else}}_None._

{{end}}## Active decisions

{{if .Decisions}}{{range .Decisions}}- {{.}}
{{end}}{{else}}_None._
{{end}}
## Runbooks

{{if .Runbooks}}{{range .Runbooks}}- {{.}}
{{end}}{{else}}_None._
{{end}}
## Knowledge

{{if .Notes}}{{range .Notes}}- {{.}}
{{end}}{{else}}_None._
{{end}}
## References

{{if .References}}{{range .References}}- {{.}}
{{end}}{{else}}_None._
{{end}}`

// contextData feeds contextTemplate; Decisions and References carry the
// already-rendered bullet text (markdown link or plain title).
type contextData struct {
	ProjectName string
	Features    []featureRow
	Epics       []epicSection
	Decisions   []string
	Runbooks    []string
	Notes       []string
	References  []string
}

type featureRow struct {
	ID, State, Parent, Module, Title, Docs string
}

// epicSection is one epic in the CONTEXT.md "Epics" breakdown: the parent
// feature with its live children and implemented/total progress.
type epicSection struct {
	ID, Title   string
	Done, Total int
	Children    []epicChild
}

type epicChild struct {
	ID, State, Title string
}

// Materialize wipes and rebuilds docsDir from the backend at repoDir,
// writing only current-state entities plus a generated CONTEXT.md. When
// scope is non-empty only features of that module are included
// (decisions and references are project-wide). It returns the manifest of
// written files: rel slash path -> sha256 hex (CONTEXT.md included,
// .gitkeep excluded).
func Materialize(repoDir, docsDir, scope string, okf bool) (map[string]string, error) {
	proj, err := store.LoadProject(repoDir)
	if err != nil {
		return nil, err
	}
	features, err := store.LoadAllFeatures(repoDir)
	if err != nil {
		return nil, err
	}
	decisions, err := store.LoadAllDecisions(repoDir)
	if err != nil {
		return nil, err
	}
	runbooks, err := store.LoadAllRunbooks(repoDir)
	if err != nil {
		return nil, err
	}
	notes, err := store.LoadAllNotes(repoDir)
	if err != nil {
		return nil, err
	}
	references, err := store.LoadAllReferences(repoDir)
	if err != nil {
		return nil, err
	}

	if err := os.RemoveAll(docsDir); err != nil {
		return nil, err
	}
	if err := os.MkdirAll(docsDir, 0o755); err != nil {
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(docsDir, ".gitkeep"), nil, 0o644); err != nil {
		return nil, err
	}

	manifest := map[string]string{}
	data := contextData{ProjectName: proj.Name}

	var shown []store.Feature // in-scope, non-terminal features, for the epic breakdown
	for _, state := range contextGroupOrder {
		for _, f := range features { // already sorted by ID
			if f.State != state {
				continue
			}
			if scope != "" && f.Module != scope {
				continue
			}
			row := featureRow{ID: f.ID, State: string(f.State), Parent: f.Parent, Module: f.Module, Title: f.Title}
			if materializedStates[f.State] {
				docs, err := copyFeatureDocs(repoDir, docsDir, f, okf, manifest)
				if err != nil {
					return nil, err
				}
				row.Docs = docs
			}
			data.Features = append(data.Features, row)
			shown = append(shown, f)
		}
	}
	data.Epics = epicSections(shown)

	for _, d := range decisions {
		if d.State != domain.DecisionActive {
			continue
		}
		meta := okfMeta{Type: "decision", Title: d.Title, Timestamp: okfTime(d.UpdatedAt)}
		line, err := copyEntry(repoDir, docsDir, "decisions", d.ID, d.Title, manifest, okf, meta)
		if err != nil {
			return nil, err
		}
		if len(d.Facets) > 0 {
			line += " · facet " + strings.Join(d.Facets, ",")
		}
		if len(d.Components) > 0 {
			line += " · comp " + strings.Join(d.Components, ",")
		}
		data.Decisions = append(data.Decisions, line)
	}

	for _, rb := range runbooks {
		if rb.State != domain.RunbookActive {
			continue
		}
		meta := okfMeta{Type: "runbook", Title: rb.Title, Timestamp: okfTime(rb.UpdatedAt)}
		line, err := copyEntry(repoDir, docsDir, "runbooks", rb.ID, rb.Title, manifest, okf, meta)
		if err != nil {
			return nil, err
		}
		data.Runbooks = append(data.Runbooks, line)
	}

	for _, n := range notes {
		if n.State != domain.NoteActive {
			continue
		}
		meta := okfMeta{Type: "note", Title: n.Title, Timestamp: okfTime(n.UpdatedAt), Informs: n.Informs}
		line, err := copyEntry(repoDir, docsDir, "notes", n.ID, n.Title, manifest, okf, meta)
		if err != nil {
			return nil, err
		}
		if len(n.Facets) > 0 {
			line += " · facet " + strings.Join(n.Facets, ",")
		}
		if len(n.Components) > 0 {
			line += " · comp " + strings.Join(n.Components, ",")
		}
		data.Notes = append(data.Notes, line)
	}

	for _, r := range references {
		if r.State != domain.ReferenceCurrent {
			continue
		}
		meta := okfMeta{Type: "reference", Title: r.Title, Timestamp: okfTime(r.UpdatedAt), Resource: r.URL, External: r.External, Informs: r.Informs}
		line, err := copyEntry(repoDir, docsDir, "references", r.ID, r.Title, manifest, okf, meta)
		if err != nil {
			return nil, err
		}
		data.References = append(data.References, line)
	}

	if err := copyWiki(repoDir, docsDir, manifest); err != nil {
		return nil, err
	}

	tmpl, err := template.New("context").Parse(contextTemplate)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}
	sum, err := writeFile(docsDir, "CONTEXT.md", buf.Bytes())
	if err != nil {
		return nil, err
	}
	manifest["CONTEXT.md"] = sum
	return manifest, nil
}

// copyWiki projects every compiled page under content/wiki/ into .docs/wiki/
// verbatim, adding each to the manifest. Wiki is a versioned synthesis
// artifact, so it is project-wide and ignores the feature scope filter. A
// backend with no compiled pages is a no-op.
func copyWiki(repoDir, docsDir string, manifest map[string]string) error {
	wikiRoot := filepath.Join(repoDir, "content", "wiki")
	return filepath.WalkDir(wikiRoot, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				return nil
			}
			return err
		}
		if d.IsDir() || !strings.HasSuffix(d.Name(), ".md") {
			return nil
		}
		body, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		under, err := filepath.Rel(wikiRoot, p)
		if err != nil {
			return err
		}
		rel := "wiki/" + filepath.ToSlash(under)
		sum, err := writeFile(docsDir, rel, body)
		if err != nil {
			return err
		}
		manifest[rel] = sum
		return nil
	})
}

// copyFeatureDocs copies the feature's existing lifecycle documents into
// current/features/<ID>-<slug>/ and returns the rendered Docs column:
// "[spec](path), [plan](path)" for the docs that exist. Under okf, each doc is
// wrapped in OKF frontmatter (type: spec|plan|result) and a generated index.md
// (type: feature) is emitted carrying the feature's lifecycle fields.
func copyFeatureDocs(repoDir, docsDir string, f store.Feature, okf bool, manifest map[string]string) (string, error) {
	dirName := entryName(f.ID, f.Title)
	var links, written []string
	for _, filename := range featureDocFilenames {
		src := filepath.Join(repoDir, "content", "features", f.ID, filename)
		body, err := os.ReadFile(src)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return "", err
		}
		if okf {
			docType := strings.TrimSuffix(filename, ".md")
			body = okfFrontmatter(okfMeta{Type: docType, Title: f.Title, Timestamp: okfTime(f.UpdatedAt)}, body)
		}
		rel := "current/features/" + dirName + "/" + filename
		sum, err := writeFile(docsDir, rel, body)
		if err != nil {
			return "", err
		}
		manifest[rel] = sum
		links = append(links, fmt.Sprintf("[%s](%s)", strings.TrimSuffix(filename, ".md"), rel))
		written = append(written, filename)
	}
	if okf {
		if err := writeFeatureIndex(docsDir, dirName, f, written, manifest); err != nil {
			return "", err
		}
	}
	return strings.Join(links, ", "), nil
}

// writeFeatureIndex emits the OKF index.md concept for a feature: a type:feature
// frontmatter carrying the lifecycle fields (state, parent, module→tags) plus
// sibling links to whichever lifecycle docs were materialized. The index is
// generated, so its cerne_id comes from the feature id.
func writeFeatureIndex(docsDir, dirName string, f store.Feature, written []string, manifest map[string]string) error {
	var tags []string
	if f.Module != "" {
		tags = []string{f.Module}
	}
	// D-0003: the facet/component axes join module in the OKF tag list.
	tags = append(tags, f.Facets...)
	tags = append(tags, f.Components...)
	meta := okfMeta{
		Type:      "feature",
		Title:     f.Title,
		Timestamp: okfTime(f.UpdatedAt),
		Tags:      tags,
		State:     string(f.State),
		Parent:    f.Parent,
		CerneID:   f.ID,
	}
	var body strings.Builder
	body.WriteString("# " + f.Title + "\n")
	for _, filename := range written {
		body.WriteString(fmt.Sprintf("\n- [%s](%s)", strings.TrimSuffix(filename, ".md"), filename))
	}
	body.WriteString("\n")
	rel := "current/features/" + dirName + "/index.md"
	sum, err := writeFile(docsDir, rel, okfFrontmatter(meta, []byte(body.String())))
	if err != nil {
		return err
	}
	manifest[rel] = sum
	return nil
}

// copyEntry copies content/<kind>/<ID>.md into current/<kind>/<ID>-<slug>.md
// and returns the CONTEXT.md bullet text: a markdown link when the content
// document exists, the plain "<ID> — <title>" otherwise.
func copyEntry(repoDir, docsDir, kind, id, title string, manifest map[string]string, okf bool, meta okfMeta) (string, error) {
	label := fmt.Sprintf("%s — %s", id, title)
	body, err := os.ReadFile(filepath.Join(repoDir, "content", kind, id+".md"))
	if errors.Is(err, os.ErrNotExist) {
		return label, nil
	}
	if err != nil {
		return "", err
	}
	if okf {
		body = okfFrontmatter(meta, body)
	}
	rel := "current/" + kind + "/" + entryName(id, title) + ".md"
	sum, err := writeFile(docsDir, rel, body)
	if err != nil {
		return "", err
	}
	manifest[rel] = sum
	return fmt.Sprintf("[%s](%s)", label, rel), nil
}

// epicSections builds the CONTEXT.md "Epics" breakdown from the features shown
// in the table: every feature that has at least one child among them, with its
// children and implemented/total progress. The caller passes only shown
// (in-scope, non-terminal) features, so children are already live; epics are
// sorted by ID. A child whose parent is not among the shown features (e.g. the
// epic itself is terminal) is left to the lint, not rendered here.
func epicSections(shown []store.Feature) []epicSection {
	byID := make(map[string]store.Feature, len(shown))
	for _, f := range shown {
		byID[f.ID] = f
	}
	childrenByParent := store.ChildrenByParent(shown)
	epicIDs := make([]string, 0, len(childrenByParent))
	for id := range childrenByParent {
		epicIDs = append(epicIDs, id)
	}
	sort.Strings(epicIDs)

	var sections []epicSection
	for _, id := range epicIDs {
		epic, ok := byID[id]
		if !ok {
			continue
		}
		children := childrenByParent[id]
		done, total := store.EpicProgress(children)
		sec := epicSection{ID: id, Title: epic.Title, Done: done, Total: total}
		for _, c := range children {
			sec.Children = append(sec.Children, epicChild{ID: c.ID, State: string(c.State), Title: c.Title})
		}
		sections = append(sections, sec)
	}
	return sections
}

// maxEntryName bounds the materialized name stem (ID + "-" + slug) used for both
// single-file entries (<stem>.md) and feature directories (<stem>/). NAME_MAX is
// 255 bytes on macOS APFS/HFS+ and most Linux filesystems; we keep a margin.
// Without this cap a very long title overflows NAME_MAX and `cerne pull` aborts
// with ENAMETOOLONG on the offending entry, blocking materialization of the whole
// snapshot for everyone on such a filesystem.
const maxEntryName = 200

// entryName joins ID and slugified title; just the ID when the title slugifies to
// nothing. The result is capped at maxEntryName bytes (trimmed back to a hyphen
// boundary when possible) so an over-long title cannot produce a name that exceeds
// the filesystem's NAME_MAX — the ID prefix keeps it unique regardless. slug.Make
// emits only [a-z0-9-], so truncating by bytes never splits a multibyte rune.
func entryName(id, title string) string {
	s := slug.Make(title)
	if s == "" {
		return id
	}
	name := id + "-" + s
	if len(name) <= maxEntryName {
		return name
	}
	name = name[:maxEntryName]
	if i := strings.LastIndexByte(name, '-'); i > len(id) {
		name = name[:i]
	}
	return strings.TrimRight(name, "-")
}

// writeFile writes body to <docsDir>/<rel> (rel slash-separated), creating
// parent dirs, and returns the sha256 hex of body.
func writeFile(docsDir, rel string, body []byte) (string, error) {
	path := filepath.Join(docsDir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(path, body, 0o644); err != nil {
		return "", err
	}
	sum := sha256.Sum256(body)
	return hex.EncodeToString(sum[:]), nil
}
