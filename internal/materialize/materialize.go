// featureDocFilenames are the lifecycle documents copied per feature, in
// the order their links appear in the CONTEXT.md Docs column.
var featureDocFilenames = []string{"spec.md", "plan.md", "result.md"}

// contextGroupOrder is the fixed display order of the CONTEXT.md feature
// table: only what is live (E-0005 criterion 1). Done, rejected and superseded
// come as a count per state; a done feature's delivery is in the code.
var contextGroupOrder = []domain.FeatureState{
	domain.StateInDevelopment,
	domain.StateApproved,
	domain.StateCandidate,
	domain.StateImplemented,
}

// contextKeepOrder is the order the table keeps live features in when they do
// not fit contextMaxBytes (E-0005 criterion 3): the last ones go first.
var contextKeepOrder = []domain.FeatureState{
	domain.StateInDevelopment,
	domain.StateImplemented,
	domain.StateApproved,
	domain.StateCandidate,
}

// contextClosedOrder is the order of the "Not listed" counts.
var contextClosedOrder = []domain.FeatureState{domain.StateDone, domain.StateRejected, domain.StateSuperseded}

// materializedStates are the feature states whose content documents are
// copied into .docs/. Implemented features stay listed in CONTEXT.md but
// their content is not materialized (promotion-on-completion rule).
var materializedStates = map[domain.FeatureState]bool{
	domain.StateCandidate:     true,
	domain.StateApproved:      true,
	domain.StateInDevelopment: true,
}

// The *IsCurrent predicates below are the single source of truth for "does the
// materializer project this entity into .docs/". Materialize and ComputeStats
// (F-0127) both use them, so the context-savings metric can never diverge from
// the entity documents the projection delivers (CONTEXT.md is not counted).

func featureIsCurrent(f store.Feature) bool     { return materializedStates[f.State] }
func decisionIsCurrent(d store.Decision) bool   { return d.State == domain.DecisionActive }
func runbookIsCurrent(rb store.Runbook) bool    { return rb.State == domain.RunbookActive }
func noteIsCurrent(n store.Note) bool           { return n.State == domain.NoteActive }
func referenceIsCurrent(r store.Reference) bool { return r.State == domain.ReferenceCurrent }

