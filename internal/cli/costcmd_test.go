// costLine is one assistant transcript line with the four counters.
func costLine(ts, id, model, agent string, in, cw, cr, out int) string {
	side := ""
	if agent != "" {
		side = `"isSidechain":true,"agentId":"` + agent + `",`
	}
	return `{"type":"assistant","timestamp":"` + ts + `","requestId":"req-` + id + `",` + side +
		`"message":{"id":"` + id + `","model":"` + model + `","usage":{"input_tokens":` + strconv.Itoa(in) +
		`,"cache_creation_input_tokens":` + strconv.Itoa(cw) + `,"cache_read_input_tokens":` + strconv.Itoa(cr) +
		`,"output_tokens":` + strconv.Itoa(out) + `}}}`
}

// writeTranscript writes lines to <CLAUDE_CONFIG_DIR>/projects/-tmp-p/<rel>.
func writeTranscript(t *testing.T, root, rel string, lines ...string) {
	t.Helper()
	p := filepath.Join(root, "projects", "-tmp-p", filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(strings.Join(lines, "\n")+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
}

func costBind(t *testing.T, cacheDir, sess, id, ts string) {
	t.Helper()
	at, err := time.Parse(time.RFC3339, ts)
	if err != nil {
		t.Fatal(err)
	}
	if err := cost.AppendBind(cacheDir, cost.Bind{Session: sess, Entity: id, Harness: cost.HarnessClaudeCode, TS: at}); err != nil {
		t.Fatal(err)
	}
}

// costProject is a project with F-0001 in state and costSessions. It returns
// the project dir and the backend clone.
func costProject(t *testing.T, state domain.FeatureState) (projDir, repoDir string) {
	t.Helper()
	projDir, _, repoDir = setupProject(t)
	now := time.Now().UTC()
	if err := store.SaveFeature(repoDir, store.Feature{ID: "F-0001", Title: "Feature F-0001", State: state, CreatedAt: now, UpdatedAt: now}); err != nil {
		t.Fatal(err)
	}
	commitBackend(t, repoDir)
	costSessions(t, repoDir)
	return projDir, repoDir
}

// costSessions binds F-0001 in sess-1 (main + subagent transcript, one
// message before the bind) and sess-2 (no transcript).
func costSessions(t *testing.T, repoDir string) {
	t.Helper()
	root := t.TempDir()
	t.Setenv("CLAUDE_CONFIG_DIR", root)
	writeTranscript(t, root, "sess-1.jsonl",
		costLine("2026-11-01T10:00:30Z", "m0", "claude-opus-5-5", "", 5, 0, 0, 5),
		costLine("2026-11-01T10:02:00Z", "m1", "claude-opus-5-5", "", 1, 10, 100, 1000))
	writeTranscript(t, root, "sess-1/subagents/agent-x.jsonl",
		costLine("2026-11-01T10:03:00Z", "m2", "claude-sonnet-5", "x", 2, 20, 200, 2000))
	cacheDir := filepath.Dir(repoDir)
	costBind(t, cacheDir, "sess-1", "F-0001", "2026-11-01T10:01:00Z")
	costBind(t, cacheDir, "sess-2", "F-0001", "2026-11-01T10:01:00Z")
}

