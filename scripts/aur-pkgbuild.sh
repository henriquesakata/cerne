#!/bin/sh
# Print the PKGBUILD of the AUR package cerne-bin for a cerne release (F-0507).
#
#   scripts/aur-pkgbuild.sh <tag> <SHA256SUMS>
#
# release.yml checks it in an Arch container (scripts/aur-check.sh) and then
# pushes it, with its .SRCINFO, to the AUR repository of cerne-bin. The package
# installs the release binary for the machine, no build and no Go, each
# architecture pinned to its asset's hash in SHA256SUMS. Only stable tags: a
# pkgver cannot hold the hyphen of a prerelease tag.
set -eu

fail() {
  echo "aur-pkgbuild: $*" >&2
  exit 1
}

[ $# -eq 2 ] || fail "usage: aur-pkgbuild.sh <tag> <SHA256SUMS>"
tag=$1
sums=$2
printf '%s\n' "$tag" | grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+$' ||
  fail "tag must look like v1.2.3 (no prerelease), got '$tag'"
[ -r "$sums" ] || fail "cannot read $sums"

# hash <os_arch>: the asset's SHA-256 from SHA256SUMS (`<hash>  <name>`).
hash() {
  h=$(awk -v n="cerne_${tag}_$1" '$2 == n || $2 == "*" n { print $1 }' "$sums")
  [ -n "$h" ] || fail "no line for cerne_${tag}_$1 in $sums"
  echo "$h"
}

# Every hash before any output: a missing asset prints no PKGBUILD.
linux_amd64=$(hash linux_amd64) || exit 1
linux_arm64=$(hash linux_arm64) || exit 1

url='https://github.com/henriquesakata/cerne/releases/download/v${pkgver}/cerne_v${pkgver}'

cat <<EOF
# Maintainer: Henrique Sakata
# Generated by scripts/aur-pkgbuild.sh in github.com/henriquesakata/cerne on each release.
pkgname=cerne-bin
pkgver=${tag#v}
pkgrel=1
pkgdesc='Living documentation for projects built with AI agents'
arch=('x86_64' 'aarch64')
url='https://github.com/henriquesakata/cerne'
license=('Apache-2.0')
provides=('cerne')
conflicts=('cerne')
options=('!strip' '!debug')
source_x86_64=("cerne-\${pkgver}-x86_64::${url}_linux_amd64")
sha256sums_x86_64=('$linux_amd64')
source_aarch64=("cerne-\${pkgver}-aarch64::${url}_linux_arm64")
sha256sums_aarch64=('$linux_arm64')

package() {
  install -Dm755 "cerne-\${pkgver}-\${CARCH}" "\${pkgdir}/usr/bin/cerne"
}
EOF
